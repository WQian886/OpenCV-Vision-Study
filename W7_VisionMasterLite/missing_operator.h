// ============================================================
// 「算子没装」这条规则 —— 只有一份
// ============================================================
//
// ⚠ 2026-10-25(欠账 18 加载期 / 欠账 19):
//   解析层已经知道哪些算子没装(GraphNode::known=false),
//   那一步**必须失败** —— 不许跑成,更不许静默 PASS。
//
//   规则住在**解析层和执行层之间** ——
//   解析层已经知道答案了,没理由再去猜。
//
// ⚠⚠ 2026-10-25 第六笔(P0-2)发现:**这条规则当时有两份实现**:
//
//   headless_runner.cpp :: guardedRunner
//       消息:"算子 X 未注册,这一步跑不了"
//   mainwindow.cpp :: runPipeline 里的 runner(内联)
//       消息:"算子 X 未注册,**跳过**"
//
//   GUI 那句是**错的**:它**没有跳过** ——
//   那一步返回了 false,引擎记成失败,整批判 ERROR。
//   用户在日志里读到「跳过」,会以为后面照跑了,
//   而结论是**整批作废**。
//
//   这就是本项目栽过**十遍**的「抄副本」的**第十一遍** ——
//   而且这一遍的两份**行为一致、消息不一致**,
//   属于最难发现的那一类:不比对两边就看不出差别。
//
//   现在收成**一份**,两边都调它。
//
// ============================================================
// 依赖面
// ============================================================
// 只依赖 QtCore(QString / QSet)。**零 OpenCV、零 QtWidgets**。
//
// ⚠ 判据是「**调用方给的事实**」,不是「纯层去问工厂」:
//   纯层不能 new 算子(OperatorBase 的头拖 opencv2),
//   而「装没装」这个**事实**是解析层知道的(known=false)。
//   纯层只负责**判**和**说**,不负责**查**。
//
// ============================================================

#include <QSet>
#include <QString>

namespace w7 {

// 没装的算子,那一步失败时说什么。
//
// ⚠ 这句话是**给用户看**的,所以它必须说清三件事:
//   哪个算子、为什么跑不了、**后果是什么**(那一步失败,不是跳过)。
inline QString missingOperatorMessage(const QString& opName) {
    return QStringLiteral("算子 %1 未注册,这一步跑不了").arg(opName);
}

// 「这个算子没装」→ 那一步**必须失败**。
//
// 返回 true = 该拒绝(调用方要 return false,并把 err 填上)。
// 返回 false = 不归这条规则管,调用方照常跑。
//
// ⚠ 这里**不碰 out**:失败那一步的输出必须是空的,
//   而「空输出」是引擎的规矩(失败步骤的输出被置空),
//   不是这里的。少写一句就可能让下游拿到上一步的残留。
inline bool rejectMissingOperator(const QString& opName,
                                  const QSet<QString>& missingOps,
                                  QString* err) {
    if (!missingOps.contains(opName)) return false;
    if (err) *err = missingOperatorMessage(opName);
    return true;
}

} // namespace w7
