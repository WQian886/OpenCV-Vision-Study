#pragma once
// ============================================================
// artifact_path.h — 中间产物落盘路径的**唯一**生成处
//
// ============================================================
// 为什么要有这个文件
//
// Run 引擎只传字符串路径,所以算子之间靠"写文件 → 下游 imread"传数据。
// 于是文件名就成了数据通路的一部分 —— 写错一次,后面每一级都读的是
// 别人的数据,而且**不崩、不报错、状态点全绿**,只有数是错的。
//
// 本项目在这件事上栽过两次,两次都不是同一个原因:
//
// ① **节点实例之间覆盖**(已修)
//     color_segment 的 mask 曾写死成 `images/w7_color_segment_mask.png`。
//     一条流水线里放两个颜色分割(抓红 + 抓蓝,很常见)时第二个覆盖第一个,
//     下游 blob_count 读到的是**第二个的 mask**。
//     修法:文件名带 `node_uuid` 前 8 位。
//
// ② **帧之间覆盖**(本文件要解决的)
//     就算带了 uuid,不带帧号也一样会覆盖:文件夹源跑 12 帧时,
//     第 0 帧的中间图被第 1 帧盖掉,再被第 2 帧盖掉……
//     跑完只剩**最后一帧**的图。
//     当时之所以没被发现,是因为每步结果查看也**只缓存最后一帧**
//     (`frame == totalFrames - 1` 才写缓存),两边一起"只留最后",
//     看起来是自洽的。要做多帧查看就必须先把这条路拆开。
//
//     现状实测(2026-10-15):带帧号的只有 color_segment 和
//     image_source_video 两个,其余 9 个写文件的算子全是固定名 ——
//     circle_fit / caliper_dist / line_fit / angle / point_line_dist /
//     point_point_dist / pcb_inspect / pcb_defect_judge / dl_infer。
//
// 所以这里把命名规则抽成一个纯函数:一个算子的落盘路径**只能**由它生成,
// 不许再在算子里手写字符串字面量。
//
// 为什么能做成纯函数
//
// 输入只有三样:算子名、node_uuid、frame_index;输出只有一个字符串。
// 不碰 QImage / cv::Mat / 画布 —— 于是能无头单测,变异验证也便宜。
//
// 关于"每帧一份会不会把磁盘撑爆"
//
// 会,所以配套有覆盖策略(见 kArtifactKeepFrames):
//   · 数字(QJsonObject)全帧留 —— 很小,一条链 8 个节点 × 2000 帧也就几 MB。
//   · 图**只留最近 N 帧**,更早的帧号在下一轮跑时被同名覆盖。
//   · 被覆盖的帧仍然能看数字,但**必须明说图没了**,不能拿后来的图顶替 ——
//     拿错帧的图配本帧的数字,比没图更坏。
// ============================================================

#include <QString>

namespace w7 {

// ============================================================
// 图保留窗口:只保留最近这么多次 Run 的帧号
//
// 2000 帧满跑 × 9 个写文件的算子 × 约 27 KB/张(实测 W6 样本均值)
// ≈ 480 MB —— 能跑,但每次 Run 都往磁盘上砸东西不合适。
// 取 50:默认流水线 12 帧全覆盖;大批量跑时旧的让位给新的。
//
// 这个数是**策略**,不是硬上限 —— 真正的闸门在框架那边,
// 这个常量只决定"第几帧开始被覆盖"。
// ============================================================
inline constexpr int kArtifactKeepFrames = 50;

// ============================================================
// 生成一个算子的中间产物路径
//
// opName     算子名,例如 "line_fit"  → 产出 w7_line_fit_*.png
// nodeUuid   Run 引擎注入的节点 UUID;为空时退回旧文件名(见下)
// frameIndex 帧号;小于 0 视为单帧调用
//
// 产出示例:
//   images/w7_line_fit_ab12cd34_f0007.png
//     └── uuid 前 8 位(区分节点实例)└─ 帧号(区分帧)
//
// 为什么 uuid 为空时**退回旧文件名**而不是报错或改名
//
// 单测直接调 `op->run(params, inputs)` 时没有 node_uuid,
// 而十几条现有断言直接 imread 那个固定路径。改成新名字会让这些
// 断言"测的是不存在的文件" —— 报红的原因和真实缺陷无关,是最坏的一种红。
// 退回旧名等于:引擎路径走新的(有 uuid + 帧号),测试路径保持原样。
// 代价是"不带 uuid 就不区分帧",但那条路只在测试里走。
//
// 帧号用 4 位零填充:排序等于帧序,而且固定宽度让"同算子同 uuid"的
// 文件名长度一致,覆盖行为可预期。
// ============================================================
inline QString artifactPath(const QString& opName,
                            const QString& nodeUuid,
                            int frameIndex = -1) {
    if (nodeUuid.isEmpty()) {
        // 测试路径:保持历史文件名不变
        return QString("images/w7_%1.png").arg(opName);
    }
    if (frameIndex < 0) {
        // 有 uuid 但没有帧号(非 Run 引擎调用):仍要区分节点实例,
        // 否则回到"两个实例互相覆盖"那个老坑。
        return QString("images/w7_%1_%2.png").arg(opName, nodeUuid.left(8));
    }
    return QString("images/w7_%1_%2_f%3.png")
        .arg(opName, nodeUuid.left(8))
        .arg(frameIndex, 4, 10, QChar('0'));
}

// ============================================================
// 这一帧的图**还在不在**
//
// 用于多帧查看时的诚实检查:文件被后来的帧覆盖掉了就是 false,
// 此时界面该说"这帧的图已被覆盖,只能看数字",
// 而不是拿最后一帧的图配这一帧的数字。
//
// 调用方通常拿实际存在的路径去 QFile::exists 一次更直接;
// 这个函数的价值是**判据本身可单测**,而且口径和命名规则放在一起,
// 不会出现"命名规则改了、判据没改"。
// ============================================================
inline bool artifactFrameIsKept(int frameIndex, int keepFrames) {
    return frameIndex >= 0 && frameIndex < keepFrames;
}

} // namespace w7
