#pragma once
// ============================================================
// frame_record — 帧循环里"把每一帧的结果记下来"的那一步
//
// ## 这份代码为什么存在
//
// 以前这一步是直接内联在 mainwindow.cpp 的帧循环里的:
//
//     m_stepCache.put(id, frame, out, tr("第 %1 步 · %2")...);
//
// 而 mainwindow.cpp **不在任何测试目标里**(它要真窗口 + 全部算子,
// 无头构造不了)。于是"每一帧都记"这条不变量只能靠 lint 读源码来保证。
//
// 实测的代价(变异 M4):把上面那行重新包回
//
//     if (frame == totalFrames - 1 || totalFrames == 1)
//
// 也就是改回这次改动之前的样子 —— 跑完整套 **12/12 全绿**,
// 没有任何一条断言发现。128 条断言一条都没碰到这段代码。
//
// 这类"改回去也没人发现"是本项目记过的第 12 条教训
// (memory/feedback-verification-doesnt-verify.md)。
//
// ## 现在怎么办
//
// 把这一步抽成**能行为测试**的函数:
//
//   1. 测试直接驱动 recordFrameResult(),跑 30 帧,断言 30 帧全在缓存里
//      —— 这条断言**会**在"只记最后一帧"时变红。
//   2. mainwindow 有没有在循环里调用它,由 lint 守(见 test_run_policy.cpp)。
//      但这条 lint 盯的是**有调用**,不是"没有某个字符串" ——
//      前者比后者强得多:原来那条 lint 换个等价写法就看不见了。
//
// ## 为什么不是"把整个帧循环抽出来"
//
// 帧循环体里有画布、算子、UI 泵、日志 —— 抽出来要动的比这件事大得多,
// 而且抽出来之后测试还是得造一堆假对象。
// 真正需要被验证的不变量只有两条:
//   (a) 每一帧的结果都被记下来了
//   (b) spin 上的序号能换算成真实帧号
// 这两条都在下面,都很小。
// ============================================================

#include <QJsonObject>
#include <QList>
#include <QString>

#include "step_frame_cache.h"

namespace w7 {

// ============================================================
// 帧循环里"把这一帧的结果记进缓存"这一步
//
// 返回值 = 被丢弃的帧数(缓存满了时 > 0)。
//
// ⚠ 缓存满了**必须报出来** —— 静默丢帧的话,界面一切正常,
//   只是用户要查的那一帧的数字**不在了**,而他不知道。
//   (mainwindow 那边的调用点会把返回值写进日志。)
//
// nodeId 为空 / cache 为空时什么都不做,返回 0 ——
// 调用点在帧循环里,每一帧都要走一遍,不能在这里抛异常或崩。
// ============================================================
inline int recordFrameResult(StepFrameCache* cache,
                             const QString& nodeId,
                             int frame,
                             const QJsonObject& out,
                             const QString& title) {
    if (!cache || nodeId.isEmpty()) return 0;
    return cache->put(nodeId, frame, out, title);
}

// ============================================================
// spin 的序号(1-based)-> 真实帧号
//
// ⚠⚠ 序号 ≠ 帧号。这是最容易搞错的一处。
//
//   缓存有上限(kStepCacheMaxFrames),满了会丢**最早**的帧。
//   所以缓存里剩下的帧号可能是 7,8,9,...,36 —— 此时
//   "第 3 个"对应的真实帧号是 **9**,不是 2。
//
//   拿 pos-1 当帧号用,在没丢帧的时候看不出问题(正好相等),
//   一旦丢了帧就**静默指错帧** —— 用户点"第 3 个",
//   看到的是另一个帧的结果,而界面上没有任何异常。
//   所以必须按**位置**查表。
//
// 返回 -1 表示越界(spin 范围之外的输入)。
// 越界时**不猜** —— 宁可不显示,也不显示一个错的帧。
// ============================================================
inline int frameNumberForPosition(const QList<int>& frames, int pos) {
    if (pos < 1 || pos > frames.size()) return -1;
    return frames.at(pos - 1);
}

// ============================================================
// 这一帧的结果要不要记进缓存
//
// 答案永远是"要"。但这个函数**故意存在**:
//
//   - 以前这个决定内联在 mainwindow.cpp 里,只能靠 lint 盯着,
//     而 lint 盯不住"换个等价写法"的情况(见文件头的变异 M4)。
//   - 现在它是一个可测试的函数,测试可以对它做变异:
//     把它改成"只记最后一帧",那条断言**立刻变红**。
//     —— 这才是"验证真的在验证"。
//
// 真实理由(见 mainwindow.cpp 里那段注释):
//   30 帧里第 7 帧判 FAIL,右键回看只能看到末帧。末帧 PASS 时
//   用户看到一张绿图,**回看这个专门用来查错的入口,反而掩盖了
//   要查的那一帧**。
//
// ⚠ frame / totalFrames 都不参与判断,但签名保留它们:
//   将来真要加"只缓存关键帧"的策略时,判断该在哪已经定好了,
//   而**加策略**和**改这条不变量**必须是两件不同的事 ——
//   后者要过测试,前者要过评审。
// ============================================================
inline bool shouldCacheFrame(int frame, int totalFrames) {
    (void)frame;
    (void)totalFrames;
    return true;
}

} // namespace w7
