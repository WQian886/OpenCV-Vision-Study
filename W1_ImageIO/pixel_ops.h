#pragma once
// ============================================================
// W1 的可测逻辑层：像素判定（练习 3 —— 把蓝色像素涂黑）
//
// ============================================================
//
// ## 为什么要有这一层
//
// W1 的 main.cpp 里，**活着的代码**是「练习 3」那一段：
// 生成一张测试图，然后逐像素遍历，把"蓝色"的像素涂成纯黑。
// 学习目标里写的 imread / imwrite / at<Vec3b> 也都在那一段里。
//
// 这段逻辑原先写在 main() 里 —— 意味着它**一条测试都没有**：
// 2026-10-26 之前，W1–W5 全是零测试。
//
// 照仓库里已有的先例做（W6 的 w6_cli.h/.cpp、W7 的 step_scope.h、
// W2 的 color_pipeline.h）：**把纯逻辑抽出来，main.cpp 调它，测试也调它**。
//
// ## 判据为什么单独成一条
//
// 「什么算蓝」是这个练习的全部知识点，而它恰恰是最容易写错的一处：
// **OpenCV 是 BGR 不是 RGB**。判据写成 px[0]（蓝通道）> 100 是对的；
// 写成 px[2] 就把红当蓝了 —— 白底 (255,255,255) 会整片被判成"蓝"，
// 于是整张图涂黑，而画面上看不出任何异常。
//
// 所以判据单独一个函数，测试直接断它：
// 白 → 不是蓝；浅蓝 → 是蓝；边界（B 正好 100、G 正好 150）→ 不是蓝。
//
// ============================================================

#include <opencv2/opencv.hpp>

namespace w1 {

// 练习 3 的那张测试图：400x300，白底 + 左半浅蓝 + 中间一条深蓝带
cv::Mat makeEx3Image();

// 「这个像素算不算蓝」的判据：
//   B 通道高（是蓝的量），G/R 通道低（不是白、不是别的颜色）
//
// ⚠ 通道顺序是 **BGR** —— px[0] 是蓝，px[2] 是红。
bool isBluePixel(const cv::Vec3b& px);

// 把图里所有「蓝」的像素涂成纯黑，返回涂了多少个
//
// 就地修改 img（练习 3 的原意就是要看到图变了）。
int paintBlueToBlack(cv::Mat& img);

}  // namespace w1
