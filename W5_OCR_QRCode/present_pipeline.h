#pragma once
// ============================================================
// present_pipeline —— W5「给人看」那一层的唯一一份实现
//
// ## 为什么要有这一层
//
// W4 那一轮把模板匹配 + ORB 从 main() 里搬进了 feature_pipeline.{h,cpp},
// 理由是:整条链外面挂着 imshow / waitKey(要显示器)和 imwrite(要写盘),
// 无头环境里这两样都做不了 ⇒ 那一层**永远只能靠人眼看** ——
// 而「人眼看」和「没看过」在报告里长得一模一样。
//
// W5 的情况**不一样**,得说清楚,免得抄错模板:
//
//   · QR 解码、tesseract 调用 —— **已经在 common/qr_ocr/ 里了**,
//     而且那一层**已经有自己的套件**
//     (common/qr_ocr/tests/test_qr_ocr.cpp,注册在 W7 的 qr_ocr 套件下,
//      36 条断言)。
//     ⇒ W5 **不重复测**它。重复测就是「抄副本」的另一种写法:
//     改了核心,两份断言各说各话,而两份都是绿的。
//
//   · W5 **自己**剩下的是「**给人看**」那一层:
//     画四边形、写串号、把 OCR 文字一行一个地列出来。
//     这一层**从来没被测过** —— 而它恰好是 W5 这个 demo 的全部内容。
//
// ## 这一层做什么、不做什么
//
// 做:纯计算 + 纯绘图(只往内存里的 cv::Mat 上画)。
// 不做:不写文件、不开窗口、不读磁盘 ——
//       所以「产物不许落源码树」这条对它**天然成立**。
//
// ## ⚠ 串号的形状:**只有这一处定义**
//
// `kSerialPattern` 是「PCB 序列号长什么样」的**唯一一份定义**。
//
// 而同一个形状在仓库里**还有第二个地方**:
// `tools/check-ci-steps.ps1` 的第 4 步(CI 的 W5 冒烟门禁)里那条正则。
//
// 这两处**不是**「一份定义 + 一份拷贝」,关系是:
//
//   · 门禁那边是**另一个证人** —— 它**独立地**从程序的输出里
//     重新认这个形状,而不是问程序「你觉得对不对」。
//     (问程序就是「尺子给自己打分」,那种检查抓不到东西。)
//   · 两边必须**认的是同一个形状** ⇒ 所以字符**必须一样**,
//     而这一点由 tests/ 里的一条断言钉住:
//     它把本文件里的 pattern 和 check-ci-steps.ps1 里那条**逐字比**。
//
// ### ⚠ 两边**怎么用**它,也不一样 —— 而且是故意的
//
//   · 门禁那边:PowerShell 的 `-match` —— **搜索**,而且**不区分大小写**。
//   · 这边:`std::regex_search`,同样**不区分大小写**。
//
// ⇒ 行为**一致**:两边都在「这一段文字里**含**一个流水号吗」。
//
// 为什么不是「整串**就是**一个流水号」?
// 因为门禁读的是程序的**输出**(前后还有别的字),
// 整串匹配对它没意义;而产品这边拿到的虽然就是那一张 QR 的内容,
// 但真实产线上 QR 里装的东西可能不止一个号。
// **两边必须问同一个问题** ——
// 不然就会出现「CI 绿着,产品说数据不对」那种最难查的错位。
//
// ============================================================

#include <opencv2/core.hpp>

#include <string>
#include <vector>

namespace w5 {

// ============================================================
// 串号
// ============================================================

// PCB 序列号的形状(唯一的定义):
//   PCB-<4 位>-<3 位>-SN:<大写字母/数字>
//
// ⚠ **不区分大小写**,也不要求整串只有它 —— 见文件头那段说明。
extern const char* const kSerialPattern;

struct Serial {
    bool found = false;      // 这一段文字里**有没有**一个像样的流水号
    std::string text;        // 认出来的那一段(原样,不改大小写)
    std::string reason;      // 没认出来时的人话(为什么)
};

// 从一段文字里找流水号。找不到不报错,只是 found=false + reason 写清楚。
Serial findSerial(const std::string& payload);

// ============================================================
// 标注
// ============================================================

// 画 QR 的四边形 + 在角点上方写 label。
//
// 角点顺序是 **左上 → 右上 → 右下 → 左下**(cv::QRCodeDetector 的约定)。
// 顺序错了画出来是个**蝴蝶结**(对角连线),不是四边形 ——
// 所以这一层按**这个顺序**连,并且测试钉的就是这件事。
//
// 角点**不是 4 个**时:什么都不画,原样返回(不崩、不猜)。
cv::Mat markQr(const cv::Mat& img,
               const std::vector<cv::Point2f>& corners,
               const std::string& label);

// 画 OCR 的框 + 标注文字(教学演示用)。
cv::Mat markOcr(const cv::Mat& img);

// ============================================================
// 文字
// ============================================================

// 把 OCR 读出来的文字按**空格**分开,空的那几个丢掉。
//
// ⚠ 只按空格分,不按换行分 —— 这是 demo 现在的行为,
// 改它会改掉「一屏看到几行字」的样子,所以这里**照原样**搬过来。
std::vector<std::string> splitTokens(const std::string& text);

// 「解出来了」那一行。
//
// ⚠ CI 的第 4 步门禁认的是**这一行里的串号**
// (它在整个输出里搜索那个形状)⇒
// 所以「串号**原样**出现在这一行里」是一条**被依赖的约定**,不是排版细节。
std::string qrDecodedLine(const std::string& payload);

} // namespace w5
